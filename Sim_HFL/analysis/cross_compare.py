#!/usr/bin/env python3
"""
cross_compare.py
----------------
複数の実験 JSONL ログ (Sim_HFL の rounds_*.jsonl, または実機相当の同フォーマット)
を読み込み、HM_satisfaction / val_acc / AP切替回数 を一枚の Markdown 表に出力する。

修論で「シミュ HFL vs シミュ baseline」「実機 vs シミュ」など複数実験を
並べて比較する図表作成に使う。

使い方 (LABEL=PATH 形式、複数指定):
  # シミュベースライン3種 + HFL を比較
  python3 analysis/cross_compare.py \\
      HFL=results/logs/rounds_xxxx_HFL.jsonl \\
      fixed=results/logs/rounds_xxxx_fixed.jsonl \\
      random=results/logs/rounds_xxxx_random.jsonl \\
      greedy=results/logs/rounds_xxxx_greedy.jsonl \\
      --output results/cross_compare.md

  # ラベル省略時 (= なし) はファイル名 stem をラベルにする
  python3 analysis/cross_compare.py results/logs/rounds_*.jsonl

注:
  - 入力 JSONL は satisfaction_summary, aggregation_complete イベントを含む形式。
  - 実機側ログをこのスクリプトで扱う場合は、同じイベント名・スキーマに正規化した
    JSONL を別ツールで先に作る (将来拡張)。
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional


@dataclass
class TrialStats:
    label: str
    log_path: Path
    rounds: int = 0
    # 満足度
    hm_sat_after_history: list[float] = field(default_factory=list)
    hm_sat_before_history: list[float] = field(default_factory=list)
    avg_sat_after_history: list[float] = field(default_factory=list)
    # 精度
    val_acc_history: list[float] = field(default_factory=list)
    # AP 切替
    n_switched_total: int = 0
    # capacity overflow (拮抗構成の指標)
    capacity_overflow_total: int = 0

    @property
    def final_hm(self) -> Optional[float]:
        return self.hm_sat_after_history[-1] if self.hm_sat_after_history else None

    @property
    def avg_hm(self) -> Optional[float]:
        return statistics.mean(self.hm_sat_after_history) if self.hm_sat_after_history else None

    @property
    def final_val_acc(self) -> Optional[float]:
        return self.val_acc_history[-1] if self.val_acc_history else None

    @property
    def avg_val_acc(self) -> Optional[float]:
        return statistics.mean(self.val_acc_history) if self.val_acc_history else None


def parse_jsonl(label: str, path: Path) -> TrialStats:
    stats = TrialStats(label=label, log_path=path)
    if not path.exists():
        print(f"[warn] file not found: {path}", file=sys.stderr)
        return stats

    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                evt = json.loads(line)
            except json.JSONDecodeError:
                continue
            ev = evt.get("event")
            if ev == "satisfaction_summary":
                hm_a = evt.get("harmonic_mean_satisfaction")
                hm_b = evt.get("harmonic_mean_satisfaction_before")
                avg_a = evt.get("avg_satisfaction")
                if hm_a is not None:
                    stats.hm_sat_after_history.append(float(hm_a))
                if hm_b is not None:
                    stats.hm_sat_before_history.append(float(hm_b))
                if avg_a is not None:
                    stats.avg_sat_after_history.append(float(avg_a))
                stats.n_switched_total += int(evt.get("n_switched", 0) or 0)
                stats.capacity_overflow_total += int(evt.get("capacity_overflow_count", 0) or 0)
                stats.rounds = max(stats.rounds, int(evt.get("round_id", 0) or 0))
            elif ev == "aggregation_complete":
                va = evt.get("avg_val_acc")
                if va is not None:
                    stats.val_acc_history.append(float(va))
    return stats


def fmt_pct(v: Optional[float]) -> str:
    return f"{v*100:.2f}%" if v is not None else "—"


def fmt_num(v: Optional[float], digits: int = 3) -> str:
    return f"{v:.{digits}f}" if v is not None else "—"


def build_markdown(trials: list[TrialStats]) -> str:
    lines = [
        "# Cross Comparison Report",
        "",
        f"Generated by `cross_compare.py` — {len(trials)} trials",
        "",
        "## サマリー表",
        "",
        "| 実験 | rounds | final HM | avg HM | final acc | avg acc | AP切替総数 | capacity_overflow |",
        "|------|-------:|---------:|-------:|----------:|--------:|----------:|------------------:|",
    ]
    for t in trials:
        lines.append(
            f"| {t.label} | {t.rounds} "
            f"| {fmt_pct(t.final_hm)} | {fmt_pct(t.avg_hm)} "
            f"| {fmt_pct(t.final_val_acc)} | {fmt_pct(t.avg_val_acc)} "
            f"| {t.n_switched_total} | {t.capacity_overflow_total} |"
        )

    lines += ["", "## HM_satisfaction (after) 推移", "", "| round | " + " | ".join(t.label for t in trials) + " |",
              "|------:" + "|------:" * len(trials) + "|"]
    max_rounds = max((len(t.hm_sat_after_history) for t in trials), default=0)
    for i in range(max_rounds):
        row = [str(i + 1)]
        for t in trials:
            v = t.hm_sat_after_history[i] if i < len(t.hm_sat_after_history) else None
            row.append(fmt_pct(v))
        lines.append("| " + " | ".join(row) + " |")

    lines += ["", "## 入力ファイル", ""]
    for t in trials:
        lines.append(f"- **{t.label}**: `{t.log_path}` ({t.rounds} rounds)")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    p = argparse.ArgumentParser(
        description="複数の Sim_HFL JSONL ログを横断比較し Markdown 表を出力",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    p.add_argument("inputs", nargs="+",
                   help="LABEL=PATH (推奨) または PATH のみ (ラベルはファイル名 stem)")
    p.add_argument("--output", default=None,
                   help="出力 Markdown パス (省略時は stdout)")
    args = p.parse_args()

    trials: list[TrialStats] = []
    for spec in args.inputs:
        if "=" in spec:
            label, path_str = spec.split("=", 1)
        else:
            path_str = spec
            label = Path(spec).stem
        trials.append(parse_jsonl(label, Path(path_str)))

    md = build_markdown(trials)

    if args.output:
        out_path = Path(args.output)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(md, encoding="utf-8")
        print(f"[ok] wrote {out_path}", file=sys.stderr)
    else:
        print(md)

    return 0


if __name__ == "__main__":
    sys.exit(main())
